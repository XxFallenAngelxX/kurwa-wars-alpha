import {createHash} from 'node:crypto';
import {readdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {root,read,generated} from './engine-build.mjs';

export function releaseVersion(){
 const host=readdirSync(resolve(root,'src/host')).filter(x=>x.endsWith('.js')).sort().map(x=>'src/host/'+x);
 const files=['index.html','gm.html','manifest.webmanifest','src/styles/shell.css','assets/registry.js',...host,...Array.from({length:5},(_,i)=>`assets/packs/assets-${i+1}.js`)];
 const hash=createHash('sha256');
 for(const file of files)hash.update(file+'\0').update(read(file)).update('\0');
 hash.update('engine\0').update(generated());
 return '// Generated by npm run build; do not edit.\nself.KW_RELEASE='+JSON.stringify(hash.digest('hex').slice(0,20))+';\n';
}
export function writeReleaseVersion(){writeFileSync(resolve(root,'generated/sw-version.js'),releaseVersion(),'utf8');}
