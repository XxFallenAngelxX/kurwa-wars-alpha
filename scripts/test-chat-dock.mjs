import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const chat=read('src/engine/features/02-chat-dialogue.js'),ui=read('src/host/browser-ui.js'),css=read('src/styles/engine/07-chat.css');
const part=(s,a,b)=>s.slice(s.indexOf(a),s.indexOf(b,s.indexOf(a)+1));
const filtered=new Function(part(chat,'function chat46Filtered(','function chat46Dock(')+'return chat46Filtered')();
const rows=[{kind:'loot',t:'a'},{kind:'dialogue',scope:'combat',t:'b'},{kind:'private',t:'c'},{kind:'combat',t:'d'}];
assert.deepEqual(filtered(rows,'all'),rows);
assert.deepEqual(filtered(rows,'combat').map(r=>r.t),['b','d']);
assert.deepEqual(filtered(rows,'private').map(r=>r.t),['c']);
assert.equal(filtered(Array.from({length:200},(_,i)=>({kind:'system',i})),'all')[0].i,50);
const scroll=new Function(part(ui,'function kwChatScrollTarget(','function kwPatchChatDock(')+'return kwChatScrollTarget')();
assert.equal(scroll('all','all',100,500,200),100);
assert.equal(scroll('all','all',290,500,200),Infinity);
assert.equal(scroll('all','loot',100,500,200),Infinity);
assert.equal(scroll(null,'all',100,500,200),Infinity);
assert.match(chat,/\$\('app'\)\.append\(el\)/);
assert.ok(!part(chat,'function chat46Open()','const world45BattleLog=').includes("modal').innerHTML"));
assert.match(chat,/panel\.inert=!chat46Expanded/);
assert.match(ui,/!kwPatchChatDock\(old\[i\],parts\[i\]\)/);
assert.match(css,/transform:translateX\(calc\(-100% \+ 39px\)\)/);
assert.match(css,/visibility:hidden; pointer-events:none/);
console.log('OK chat dock: filters, ordering, scroll follow, isolated overlay');
